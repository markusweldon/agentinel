"""Map Claude Code tool calls to Rule-of-Two legs.

MCP tools (``mcp__<server>__<tool>``) come from a policy file generated by ``agentinel guard init``
from a real scan. Claude Code's built-in tools are classified here *per call*, from their input,
because the same tool can be harmless or sensitive depending on what it touches: ``Read`` of
``src/app.py`` is nothing, ``Read`` of ``.env`` is sensitive data.

These rules are a first cut for a research prototype. They are meant to be measured (see
``agentinel guard replay``) and tightened, not trusted.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

from .core import A, B, C, guard_home

POLICY_FILE = "guard-policy.json"

# --- sensitive paths (B) -------------------------------------------------------------------------
_SENSITIVE_PATHS = [
    r"(^|/)\.env($|\.(?!example$|sample$|template$|dist$)[\w.-]+$)",
    r"(^|/)\.(ssh|aws|gnupg|kube|docker|azure|config/gcloud)(/|$)",
    r"(^|/)\.(netrc|npmrc|pypirc|git-credentials|pgpass)$",
    r"(^|/)id_(rsa|ecdsa|ed25519|dsa)$",
    r"\.(pem|key|p12|pfx|jks|keystore)$",
    # A file *named* like a secret store, but only data/config files: secrets.yaml, credentials.json,
    # db-password.txt. Source files (secret_scanning.py) and bare words in commands don't count.
    r"(^|/)[^/]*(secret|credential|password)s?[^/]*\.(json|ya?ml|toml|ini|cfg|conf|txt|env|properties)$",
    r"(^|/)(credentials|secrets)$",
]
_SENSITIVE_RE = re.compile("|".join(f"(?:{p})" for p in _SENSITIVE_PATHS), re.IGNORECASE)


def is_sensitive_path(path: str) -> bool:
    return bool(path) and bool(_SENSITIVE_RE.search(path.strip().strip("\"'")))


def _looks_like_path(token: str) -> bool:
    return "/" in token or token.startswith(".") or "." in token.rsplit("/", 1)[-1]


# --- shell commands ------------------------------------------------------------------------------
_EGRESS = re.compile(
    r"\b(curl|wget|nc|ncat|netcat|telnet|ssh|scp|sftp|rsync|ftp|sendmail|mail)\b"
    r"|\bgit\s+push\b"
    r"|\bgh\s+(api|gist\s+create|release\s+(create|upload)|(pr|issue)\s+(create|comment|edit|merge|review))\b"
    r"|\b(npm|pnpm|yarn)\s+publish\b|\btwine\s+upload\b|\bdocker\s+push\b"
    r"|\baws\s+s3\s+(cp|sync|mv)\b"
    r"|\b(requests|urllib|httpx|aiohttp)\b|\bfetch\(",
    re.IGNORECASE,
)
_FETCHES_UNTRUSTED = re.compile(
    r"\b(curl|wget)\b|\bgh\s+(api|(pr|issue)\s+(view|list|diff))\b",
    re.IGNORECASE,
)
_READS_SECRETS = re.compile(
    r"(^|[;&|]\s*)(printenv|env)\s*($|[;&|>])"
    r"|\bsecurity\s+find-(generic|internet)-password\b"
    r"|\baws\s+configure\s+get\b|\bgh\s+auth\s+token\b|\bgcloud\s+auth\s+print-access-token\b"
    r"|\$\{?[A-Z0-9_]*(TOKEN|SECRET|PASSWORD|API_KEY|PRIVATE_KEY)\b",
    re.IGNORECASE,
)


def bash_legs(command: str) -> set[str]:
    legs: set[str] = set()
    if _FETCHES_UNTRUSTED.search(command):
        legs.add(A)
    if _READS_SECRETS.search(command) or any(
        _looks_like_path(tok) and is_sensitive_path(tok) for tok in re.split(r"[\s=<>|;&()'\"]+", command)
    ):
        legs.add(B)
    if _EGRESS.search(command):
        legs.add(C)
    return legs


# --- policy (MCP tools) --------------------------------------------------------------------------
def load_policy(cwd: str | None = None) -> dict[str, set[str]]:
    """Merge the user policy and the project policy (project wins). Missing files are fine."""
    candidates = [guard_home() / POLICY_FILE]
    if cwd:
        candidates.append(Path(cwd) / ".agentinel" / POLICY_FILE)
    env = os.environ.get("AGENTINEL_GUARD_POLICY")
    if env:
        candidates.append(Path(env))
    policy: dict[str, set[str]] = {}
    for path in candidates:
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError):
            continue
        for name, legs in (data.get("tools") or {}).items():
            policy[str(name)] = {leg for leg in str(legs) if leg in (A, B, C)}
    return policy


# An MCP tool the policy doesn't know. Judge it from its name, and for C count only tools that
# *send* something to someone else. Local state changes (update_plan, set_title) can't leak data,
# which is why this is narrower than the static scanner's C axis ("changes state or communicates").
_MCP_A = re.compile(
    r"fetch|navigate|browse|scrape|crawl|search|read_page|page_text|get_page|issue|pull_request|comment"
    r"|email|mail|message|thread|slack|channel|inbox|tweet|post",
    re.IGNORECASE,
)
_MCP_B = re.compile(r"secret|credential|password|token|private|vault|keychain|_env|ssn|payroll", re.IGNORECASE)
_MCP_C = re.compile(
    r"(^|_)(send|post|publish|push|upload|share|email|reply|forward|comment|tweet|webhook|notify"
    r"|navigate|create_(pull_request|issue|gist|draft|message)|merge|request)(_|$)",
    re.IGNORECASE,
)


def _mcp_fallback(tool_name: str) -> set[str]:
    parts = tool_name.split("__", 2)
    bare = parts[2] if len(parts) == 3 else tool_name
    legs: set[str] = set()
    if _MCP_A.search(bare) and not re.match(r"(send|post|create|reply|forward|update|delete)_", bare, re.I):
        legs.add(A)
    if _MCP_B.search(bare):
        legs.add(B)
    if _MCP_C.search(bare):
        legs.add(C)
    return legs


def legs_for(tool_name: str, tool_input: dict | None, policy: dict[str, set[str]] | None = None) -> set[str]:
    """The legs a single Claude Code tool call touches."""
    tin = tool_input if isinstance(tool_input, dict) else {}
    policy = policy or {}
    if tool_name in policy:
        return set(policy[tool_name])
    if tool_name.startswith("mcp__"):
        return _mcp_fallback(tool_name)
    if tool_name == "WebFetch":
        return {A, C}  # reads attacker-controllable pages; the URL itself can carry data out
    if tool_name == "WebSearch":
        return {A}
    if tool_name in ("Read", "NotebookRead"):
        return {B} if is_sensitive_path(str(tin.get("file_path") or tin.get("notebook_path") or "")) else set()
    if tool_name == "Grep":
        return {B} if is_sensitive_path(str(tin.get("path") or "")) else set()
    if tool_name == "Bash":
        return bash_legs(str(tin.get("command") or ""))
    return set()


def source_label(tool_name: str, tool_input: dict | None) -> str:
    """A short, local-only label for where a leg came from, shown in the approval prompt."""
    tin = tool_input if isinstance(tool_input, dict) else {}
    path = tin.get("file_path") or tin.get("notebook_path") or tin.get("path")
    if path:
        return f"{tool_name} {Path(str(path)).name}"
    if tool_name == "Bash":
        first = str(tin.get("command") or "").strip().split(" ", 1)[0]
        return f"Bash {first}" if first else "Bash"
    if tool_name == "WebFetch" and tin.get("url"):
        host = re.sub(r"^https?://", "", str(tin["url"])).split("/", 1)[0]
        return f"WebFetch {host}"
    return tool_name
